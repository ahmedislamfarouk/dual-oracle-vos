#!/usr/bin/env python3
"""CPD-1 frozen cross-proposer decomposition runner.

This program intentionally separates the GT-free run from evaluation: proposal
generation, ranking, SAM2 propagation, and commitment run before annotation
pixels are opened.  Ground truth is then used only to calculate the frozen
A/B/C outcomes and committed-set Hungarian metrics.

It is a driver, not a result: pass an explicit smoke manifest for Gate 1.  No
implicit video cap, random subset, or result-directory default is provided.
"""
