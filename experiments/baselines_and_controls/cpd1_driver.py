TARGET_WH = (854, 480)
TOPK = 10
PROPOSAL_THRESH = 0.05
AMG_SETTINGS = dict(points_per_side=16, pred_iou_thresh=0.80,
                    stability_score_thresh=0.90, box_nms_thresh=0.50,
                    min_mask_region_area=400)
COMMIT_SETTINGS = dict(persistence_min=0.50, area_max=0.50, dedup_temporal_iou=0.50)


def die(message: str) -> None:
    raise SystemExit(f"CPD-1 error: {message}")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def write_json_atomic(path: Path, payload: dict[str, Any]) -> None:
    """Write a restart-safe checkpoint without exposing a partial JSON file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent,
                                     prefix=f".{path.name}.", suffix=".tmp", delete=False) as f:
        json.dump(payload, f, indent=2, sort_keys=True)
        f.write("\n")
        temp_name = f.name
    os.replace(temp_name, path)


def write_status_markdown(path: Path, result: dict[str, Any], total: int) -> None:
    """Human-readable progress only; the JSON remains the evidence record."""
    path.parent.mkdir(parents=True, exist_ok=True)
    done = len(result["videos"])
    state = result.get("run_status", "running")
    lines = ["# CPD-1 shard live status", "", f"- Status: **{state}**",
             f"- Completed: **{done}/{total}** videos",
             f"- Proposer: `{result['config']['proposer']}`",
             f"- Shard: `{result['config']['shard_index']}/{result['config']['num_shards']}`",
             f"- Boundary cache: `{result['config']['boundary_cache']}`",
             f"- Video state offloaded to CPU: `{result['config']['offload_video_to_cpu']}`"]
    if result["videos"]:
        latest = result["videos"][-1]
        lines.append(f"- Last completed video: `{latest['video_id']}` ({latest['wall_seconds']:.1f}s)")
    lines.append("")
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text("\n".join(lines), encoding="utf-8")
    os.replace(tmp, path)


def box_iou(a: Iterable[float], b: Iterable[float]) -> float:
    ax1, ay1, ax2, ay2 = map(float, a); bx1, by1, bx2, by2 = map(float, b)
    ix1, iy1, ix2, iy2 = max(ax1, bx1), max(ay1, by1), min(ax2, bx2), min(ay2, by2)
    inter = max(0., ix2 - ix1) * max(0., iy2 - iy1)
    union = max(0., ax2 - ax1) * max(0., ay2 - ay1) - inter
    return inter / union if union > 0 else 0.0


def mask_box(mask: np.ndarray) -> list[float] | None:
    """Tight xyxy box, or None for an empty GT instance."""
    ys, xs = np.where(mask.astype(bool))
    if not len(xs):
        return None
    return [float(xs.min()), float(ys.min()), float(xs.max() + 1), float(ys.max() + 1)]


def mask_j(pred: np.ndarray, gt: np.ndarray) -> float:
    p, g = pred.astype(bool), gt.astype(bool)
    union = np.logical_or(p, g).sum()
    return float(np.logical_and(p, g).sum() / union) if union else float(not p.any() and not g.any())


def mask_f(pred: np.ndarray, gt: np.ndarray) -> float:
    # Canonical release implementation, imported only for GT-side evaluation.
    from metrics import compute_f_score
    return float(compute_f_score(pred, gt))


def mask_f_from_boundaries(pred_boundary: np.ndarray, gt_boundary: np.ndarray) -> float:
    """Exact arithmetic of canonical ``compute_f_score`` after boundary caching.

    The canonical metric recomputes both morphological boundaries for every
    candidate-track/GT-object pairing.  They depend only on one mask, so this
    helper reuses boundaries generated by the canonical private helper and
    preserves the remaining arithmetic verbatim.  ``--verify-boundary-cache``
    compares every cached score with ``compute_f_score`` in a smoke run before
    this optimization may be used for a reportable experiment.
    """
    if pred_boundary.sum() == 0:
        precision = 0.0
    else:
        precision = float((pred_boundary & gt_boundary).sum()) / pred_boundary.sum()
    if gt_boundary.sum() == 0:
        recall = 1.0
    else:
        recall = float((pred_boundary & gt_boundary).sum()) / gt_boundary.sum()
    if precision + recall == 0:
        return 0.0
    return 2 * precision * recall / (precision + recall)


def temporal_iou(first: list[np.ndarray], second: list[np.ndarray]) -> float:
    inter = union = 0
    for a, b in zip(first, second):
        inter += int(np.logical_and(a, b).sum()); union += int(np.logical_or(a, b).sum())
    return inter / union if union else 0.0


@dataclass(frozen=True)
class Video:
    video_id: str
    frame_paths: tuple[Path, ...]
    annotation_paths: dict[str, Path]


def _image_stem(path: Path) -> str:
    return path.stem


def find_videos(root: Path, dataset: str, split: str) -> dict[str, Video]:
    """Read official-style layouts without reading annotation image pixels."""
    if dataset == "davis":
        image_root = root / "JPEGImages" / "480p"; ann_root = root / "Annotations" / "480p"
        split_file = root / "ImageSets" / "2017" / f"{split}.txt"
        ids = [x.strip() for x in split_file.read_text().splitlines() if x.strip()] if split_file.exists() else sorted(p.name for p in image_root.iterdir() if p.is_dir())
    elif dataset in {"ytvos", "lvos", "generic"}:
        base = root / split if (root / split / "JPEGImages").is_dir() else root
        image_root = base / "JPEGImages"; ann_root = base / "Annotations"
        ids = sorted(p.name for p in image_root.iterdir() if p.is_dir())
    else:
        die(f"unsupported dataset {dataset}")
    if not image_root.is_dir() or not ann_root.is_dir():
        die(f"expected JPEGImages and Annotations below {root} (split={split})")
    videos: dict[str, Video] = {}
    for vid in ids:
        fp = sorted((image_root / vid).glob("*.jpg")) + sorted((image_root / vid).glob("*.jpeg"))
        ap = {p.stem: p for p in (ann_root / vid).glob("*.png")}
        if fp:
            videos[vid] = Video(vid, tuple(fp), ap)
    return videos


def select_videos(videos: dict[str, Video], manifest_path: Path | None, query_index: int) -> list[tuple[Video, Path]]:
    if manifest_path is None:
        return [(v, v.frame_paths[query_index]) for v in videos.values() if len(v.frame_paths) > query_index]
    data = json.loads(manifest_path.read_text())
    entries = data["videos"] if isinstance(data, dict) else data
    selected: list[tuple[Video, Path]] = []
    for x in entries:
        vid = x["video_id"]
        if vid not in videos: die(f"manifest video not found: {vid}")
        v = videos[vid]
        frame = x.get("query_frame")
        if frame is None: die(f"manifest entry {vid} has no explicit query_frame")
        matches = [p for p in v.frame_paths if p.name == frame or p.stem == str(frame)]
        if len(matches) != 1: die(f"manifest query frame not found exactly once: {vid}/{frame}")
        selected.append((v, matches[0]))
    if not selected: die("manifest selects no videos")
    return selected


def load_detr(device: str):
    from transformers import DetrForObjectDetection, DetrImageProcessor
    processor = DetrImageProcessor.from_pretrained("facebook/detr-resnet-50", revision="no_timm")
    model = DetrForObjectDetection.from_pretrained("facebook/detr-resnet-50", revision="no_timm").to(device).eval()
    def propose(rgb: np.ndarray) -> list[dict[str, Any]]:
        import torch
        inputs = {k: v.to(device) for k, v in processor(images=Image.fromarray(rgb), return_tensors="pt").items()}
        with torch.inference_mode(): out = model(**inputs)
        probs = out.logits[0].softmax(-1); score = 1.0 - probs[:, -1]
        cx, cy, w, h = out.pred_boxes[0].unbind(-1); H, W = rgb.shape[:2]
        boxes = np.stack([(cx-w/2).detach().cpu().numpy()*W, (cy-h/2).detach().cpu().numpy()*H,
                          (cx+w/2).detach().cpu().numpy()*W, (cy+h/2).detach().cpu().numpy()*H], axis=1)
        return [dict(box=[float(z) for z in b], score=float(s), native_id=f"detr:{i}")
                for i, (b, s) in enumerate(zip(boxes, score.detach().cpu().numpy())) if s >= PROPOSAL_THRESH]
    return propose, "facebook/detr-resnet-50"


def load_maskrcnn(device: str):
    import torch
    from torchvision.models.detection import MaskRCNN_ResNet50_FPN_Weights, maskrcnn_resnet50_fpn
    weights = MaskRCNN_ResNet50_FPN_Weights.DEFAULT
    model = maskrcnn_resnet50_fpn(weights=weights).to(device).eval()
    preprocess = weights.transforms()
    def propose(rgb: np.ndarray) -> list[dict[str, Any]]:
        image = torch.from_numpy(rgb).permute(2, 0, 1).float() / 255.
        with torch.inference_mode(): output = model([preprocess(image).to(device)])[0]
        return [dict(box=[float(z) for z in box], score=float(score), native_id=f"maskrcnn:{i}")
                for i, (box, score) in enumerate(zip(output["boxes"].cpu().numpy(), output["scores"].cpu().numpy()))
                if score >= PROPOSAL_THRESH]
    return propose, "torchvision.maskrcnn_resnet50_fpn:DEFAULT"


def load_amg(device: str, sam2_cfg: str, sam2_ckpt: str):
    from sam2.build_sam import build_sam2
    try:
        from sam2.automatic_mask_generator import SAM2AutomaticMaskGenerator
    except ImportError as exc:
        die(f"SAM2AutomaticMaskGenerator unavailable: {exc}")
    model = build_sam2(sam2_cfg, sam2_ckpt, device=device)
    generator = SAM2AutomaticMaskGenerator(model, **AMG_SETTINGS)
    def propose(rgb: np.ndarray) -> list[dict[str, Any]]:
        masks = generator.generate(rgb)
        result = []
        for i, item in enumerate(masks):
            x, y, w, h = item["bbox"]
            result.append(dict(box=[float(x), float(y), float(x+w), float(y+h)],
                               score=float(item["predicted_iou"]), native_id=f"amg:{i}"))
        return result
    return propose, f"SAM2-AMG:{sam2_ckpt}"


def run_propagator(frames: list[np.ndarray], selected: list[dict[str, Any]], args: argparse.Namespace) -> tuple[dict[str, list[np.ndarray]], dict[str, list[float]]]:
    # A proposer may legitimately return no boxes after the frozen threshold.
    # This is an all-miss outcome, not a SAM2 invocation: preserve it for
    # evaluation instead of asking SAM2 to propagate an empty prompt set.
    if not selected:
        return {}, {}
    import torch
    from sam2.build_sam import build_sam2_video_predictor
    predictor = build_sam2_video_predictor(args.sam2_config, args.sam2_checkpoint, device=args.device)
    tmp = Path(tempfile.mkdtemp(prefix="cpd1_frames_")); h, w = TARGET_WH[1], TARGET_WH[0]
    try:
        for i, frame in enumerate(frames): cv2.imwrite(str(tmp / f"{i:05d}.jpg"), cv2.cvtColor(frame, cv2.COLOR_RGB2BGR))
        masks = {x["track_id"]: [np.zeros((h, w), np.uint8) for _ in frames] for x in selected}
        confidence = {x["track_id"]: [] for x in selected}
        id_to_track = {i + 1: x["track_id"] for i, x in enumerate(selected)}
        with torch.inference_mode(), torch.autocast("cuda", dtype=torch.bfloat16, enabled=args.device.startswith("cuda")):
            state = predictor.init_state(video_path=str(tmp), offload_video_to_cpu=args.offload_video_to_cpu)
            for oid, item in enumerate(selected, 1): predictor.add_new_points_or_box(state, frame_idx=item["query_frame_index"], obj_id=oid, box=np.asarray([item["box"]], np.float32))
            for fi, object_ids, logits in predictor.propagate_in_video(state):
                if fi >= len(frames): break
                for oid, logit in zip(object_ids, logits):
                    tid = id_to_track.get(int(oid))
                    if tid is None: continue
                    array = logit[0].float().cpu().numpy(); mask = (array > 0).astype(np.uint8)
                    if mask.shape != (h, w): mask = cv2.resize(mask, TARGET_WH, interpolation=cv2.INTER_NEAREST)
                    masks[tid][fi] = mask; pos = array[array > 0]; confidence[tid].append(float(pos.mean()) if pos.size else 0.)
            predictor.reset_state(state)
        return masks, confidence
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def evaluate(video: Video, query_index: int, tracks: list[dict[str, Any]], masks: dict[str, list[np.ndarray]], committed: set[str], verify_boundary_cache: bool = False, evaluation_workers: int = 1) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    # This is deliberately the first point at which annotation images are read.
    ordered = [(i, p) for i, p in enumerate(video.frame_paths) if p.stem in video.annotation_paths]
    if not ordered: return [], dict(strict_jf=0., committed_precision=0., committed_recall=0., gt_count=0)
    gt_images = [(fi, cv2.resize(np.array(Image.open(video.annotation_paths[p.stem])), TARGET_WH, interpolation=cv2.INTER_NEAREST)) for fi, p in ordered]
    gt_ids = sorted({int(x) for _, mask in gt_images for x in np.unique(mask) if x > 0})
    query_gt = next((mask for fi, mask in gt_images if fi == query_index), None)
    if query_gt is None:
        # There is no honest GT-side definition of query-visible objects when the
        # query image is unannotated.  Do not silently substitute a later frame.
        return [], dict(strict_jf=0., committed_precision=0., committed_recall=0., gt_count=0,
                        all_annotated_object_count=len(gt_ids), query_annotation_available=False,
                        structural_single_shot_blind_spot_count=len(gt_ids))
    # Cache only the canonical boundary transform.  This removes duplicate CPU
    # morphology across the candidate-track x object score matrix without
    # changing masks, frame set, matching, or metric arithmetic.
    from metrics import _mask_to_boundary
    query_visible_ids = sorted(int(x) for x in np.unique(query_gt) if x > 0)
    nonquery_ids = sorted(set(gt_ids) - set(query_visible_ids))
    gt_boundaries = [(fi, {gid: _mask_to_boundary(gt == gid) for gid in gt_ids}) for fi, gt in gt_images]
    pred_boundaries = {tid: [_mask_to_boundary(mask) for mask in track_masks]
                       for tid, track_masks in masks.items()}
    # Pair scores are independent after masks and GT-side boundaries have been
    # materialized.  ``evaluation_workers`` changes scheduling only: tasks are
    # generated in a fixed order and results are collected in that same order.
    # The default one-worker path is intentionally bit-for-bit the old serial
    # computation.  A multi-worker run requires a separate parity gate before
    # it may supply paper evidence.
    def score_pair(key: tuple[str, int]) -> tuple[tuple[str, int], float]:
        """Post-hoc J&F across every annotated frame for one track/object pair."""
        track_id, gid = key
        values = []
        for (fi, gt), (_, boundary_by_gid) in zip(gt_images, gt_boundaries):
            pred = masks[track_id][fi]; target = (gt == gid).astype(np.uint8)
            f = mask_f_from_boundaries(pred_boundaries[track_id][fi], boundary_by_gid[gid])
            if verify_boundary_cache:
                reference = mask_f(pred, target)
                if not math.isclose(f, reference, rel_tol=0.0, abs_tol=0.0):
                    die(f"boundary-cache parity failure for {video.video_id}/{track_id}/{gid}/frame{fi}: {f} != {reference}")
            values.append((mask_j(pred, target) + f) / 2.)
        return key, float(np.mean(values))

    all_track_ids = [t["track_id"] for t in tracks]
    committed_list = [t["track_id"] for t in tracks if t["track_id"] in committed]
    needed_pairs = [(tid, gid) for gid in query_visible_ids for tid in all_track_ids]
    known_pairs = set(needed_pairs)
    for tid in committed_list:
        for gid in gt_ids:
            if (tid, gid) not in known_pairs:
                needed_pairs.append((tid, gid))
                known_pairs.add((tid, gid))
    needed_pairs = list(dict.fromkeys(needed_pairs))
    if evaluation_workers == 1:
        scored_pairs = [score_pair(key) for key in needed_pairs]
    else:
        with ThreadPoolExecutor(max_workers=evaluation_workers, thread_name_prefix="cpd1-jf") as pool:
            scored_pairs = list(pool.map(score_pair, needed_pairs))
    pair_jf = dict(scored_pairs)
    records: list[dict[str, Any]] = []

    def mean_track_jf(track_id: str, gid: int) -> float:
        return pair_jf[track_id, gid]
    for gid in query_visible_ids:
        # A is evaluated only for objects that exist in the actual, GT-free query
        # image.  GT is used after the run solely to identify that fixed denominator.
        target_box = mask_box(query_gt == gid)
        a_ids = [t["track_id"] for t in tracks if target_box is not None and box_iou(t["box"], target_box) >= .5]
        scores = {t["track_id"]: mean_track_jf(t["track_id"], gid) for t in tracks}
        b_ids = [tid for tid in a_ids if scores[tid] >= .5]
        c_ids = [tid for tid in b_ids if tid in committed]
        records.append(dict(object_id=gid, query_visible=True, query_frame_index=query_index, A=bool(a_ids), B=bool(b_ids), C=bool(c_ids), proposal_hit_track_ids=a_ids, propagation_hit_track_ids=b_ids, commitment_hit_track_ids=c_ids, track_mean_jf=scores))
    if committed_list and gt_ids:
        # Operational strict metric intentionally includes *all* annotated GT
        # objects.  This makes late objects visible as zero/unmatched outcomes,
        # while the causal A/B/C decomposition remains query-visible only.
        matrix = np.array([[pair_jf[tid, gid] for gid in gt_ids] for tid in committed_list])
        rows, cols = linear_sum_assignment(-matrix); assigned = {c: matrix[r, c] for r, c in zip(rows, cols)}
        strict = float(sum(assigned.values()) / len(gt_ids)); hits = sum(v >= .5 for v in assigned.values())
        precision = hits / len(committed_list); recall = hits / len(gt_ids)
    else: strict = precision = recall = 0.
    return records, dict(strict_jf=strict, committed_precision=precision, committed_recall=recall,
                         gt_count=len(query_visible_ids), all_annotated_object_count=len(gt_ids),
                         query_annotation_available=True,
                         structural_single_shot_blind_spot_count=len(nonquery_ids),
                         structural_single_shot_blind_spot_object_ids=nonquery_ids,
                         committed_count=len(committed_list), assignment_metric="mean_annotated_frame_JF")


def main() -> None:
    p = argparse.ArgumentParser(formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    p.add_argument("--dataset", choices=["davis", "ytvos", "lvos", "generic"], required=True); p.add_argument("--dataset-root", type=Path, required=True); p.add_argument("--split", default="val")
    p.add_argument("--proposer", choices=["detr", "maskrcnn", "amg"], required=True); p.add_argument("--sam2-repo", type=Path, required=True); p.add_argument("--sam2-config", required=True); p.add_argument("--sam2-checkpoint", required=True)
    p.add_argument("--canonical-source", type=Path, required=True); p.add_argument("--output", type=Path, required=True); p.add_argument("--smoke-manifest", type=Path); p.add_argument("--query-frame-index", type=int, default=0); p.add_argument("--device", default=os.environ.get("CPD1_DEVICE", "cuda")); p.add_argument("--overwrite", action="store_true")
    p.add_argument("--offload-video-to-cpu", action=argparse.BooleanOptionalAction, default=True, help="keep SAM2 video state in CPU RAM; disable only after a memory/parity smoke")
    p.add_argument("--verify-boundary-cache", action="store_true", help="compare every cached contour F-score to the canonical metric; smoke-only")
    p.add_argument("--evaluation-workers", type=int, default=1, help="parallel CPU workers for independent exact track/object scores; use >1 only after a parity smoke")
    p.add_argument("--num-shards", type=int, default=1, help="deterministic video-ID shard count for a new run")
    p.add_argument("--shard-index", type=int, default=0, help="zero-based deterministic shard index")
    p.add_argument("--checkpoint-every", type=int, default=1, help="atomically persist the JSON after this many completed videos")
    p.add_argument("--resume", action="store_true", help="resume only an exactly matching shard JSON")
    p.add_argument("--status-markdown", type=Path, help="atomically update a concise live-status Markdown file")
    args = p.parse_args()
    if TOPK != 10 or TARGET_WH != (854, 480): die("frozen constants were altered")
    if args.output.exists() and not (args.overwrite or args.resume): die(f"output exists: {args.output}; use --resume for an exact matching shard or --overwrite")
    if args.query_frame_index < 0: die("query frame index must be non-negative")
    if args.num_shards < 1 or not 0 <= args.shard_index < args.num_shards: die("invalid shard index/count")
    if args.checkpoint_every < 1: die("checkpoint-every must be positive")
    if args.evaluation_workers < 1: die("evaluation-workers must be positive")
    for need in [args.dataset_root, args.sam2_repo, args.canonical_source, Path(args.sam2_checkpoint)]:
        if not need.exists(): die(f"missing required path: {need}")
    sys.path[:0] = [str(args.sam2_repo), str(args.canonical_source)]
    videos = find_videos(args.dataset_root, args.dataset, args.split); selected_all = select_videos(videos, args.smoke_manifest, args.query_frame_index)
    chosen = [(source_ordinal, video, query) for source_ordinal, (video, query) in enumerate(selected_all, 1)
              if (source_ordinal - 1) % args.num_shards == args.shard_index]
    if not chosen: die("this shard selects no videos")
    if args.proposer == "detr": proposer, proposer_id = load_detr(args.device)
    elif args.proposer == "maskrcnn": proposer, proposer_id = load_maskrcnn(args.device)
    else: proposer, proposer_id = load_amg(args.device, args.sam2_config, args.sam2_checkpoint)
    frozen_constants = dict(resolution=list(TARGET_WH), topk=TOPK, proposal_threshold=PROPOSAL_THRESH, amg=AMG_SETTINGS, commitment=COMMIT_SETTINGS)
    config = dict(dataset=args.dataset, dataset_root=str(args.dataset_root), split=args.split, proposer=args.proposer, proposer_id=proposer_id, query_policy=("explicit_manifest" if args.smoke_manifest else f"fixed_frame_index:{args.query_frame_index}"), sam2_checkpoint=str(args.sam2_checkpoint), sam2_checkpoint_sha256=sha256(Path(args.sam2_checkpoint)), offload_video_to_cpu=args.offload_video_to_cpu, boundary_cache="canonical_private_boundary_v1", boundary_cache_verified=args.verify_boundary_cache, evaluation_workers=args.evaluation_workers, num_shards=args.num_shards, shard_index=args.shard_index, selected_video_count=len(chosen), runtime_allocator=dict(pytorch_no_cuda_memory_caching=os.environ.get("PYTORCH_NO_CUDA_MEMORY_CACHING", "0"), pytorch_alloc_conf=os.environ.get("PYTORCH_ALLOC_CONF", "")))
    if args.resume:
        if not args.output.exists(): die(f"cannot resume missing output: {args.output}")
        result = json.loads(args.output.read_text())
        if result.get("schema_version") != "cpd1-v1" or result.get("frozen_constants") != frozen_constants or result.get("config") != config:
            die("resume output does not exactly match this frozen shard configuration")
        allowed = {video.video_id for _, video, _ in chosen}
        completed = [x.get("video_id") for x in result.get("videos", [])]
        if len(completed) != len(set(completed)) or not set(completed).issubset(allowed): die("resume output has duplicate or out-of-shard video IDs")
    else:
        result = dict(schema_version="cpd1-v1", frozen_constants=frozen_constants, config=config, videos=[])
    result["run_status"] = "running"
    import torch
    completed_ids = {x["video_id"] for x in result["videos"]}
    pending = [(source_ordinal, video, query_path) for source_ordinal, video, query_path in chosen if video.video_id not in completed_ids]
    if args.status_markdown: write_status_markdown(args.status_markdown, result, len(chosen))
    for completed_ordinal, (source_ordinal, video, query_path) in enumerate(pending, len(completed_ids) + 1):
        started = time.time(); torch.cuda.reset_peak_memory_stats() if args.device.startswith("cuda") else None
        frames = [cv2.resize(cv2.cvtColor(cv2.imread(str(x)), cv2.COLOR_BGR2RGB), TARGET_WH) for x in video.frame_paths]
        query_index = next(i for i, x in enumerate(video.frame_paths) if x == query_path)
        native = proposer(frames[query_index]); native.sort(key=lambda x: (-x["score"], x["native_id"]))
        selected = [dict(x, track_id=f"{video.video_id}:track:{i:02d}", query_frame_index=query_index) for i, x in enumerate(native[:TOPK])]
        masks, conf = run_propagator(frames, selected, args)
        committed: set[str] = set(); signals = {}
        for item in selected:
            tid = item["track_id"]; areas = [int(x.sum()) for x in masks[tid]]; nonempty = [x for x in areas if x]
            signals[tid] = dict(persistence=len(nonempty)/len(frames), mean_area=(float(np.mean(nonempty))/(TARGET_WH[0]*TARGET_WH[1]) if nonempty else 0.), mean_confidence=float(np.mean(conf[tid])) if conf[tid] else 0.)
            signals[tid]["quality"] = signals[tid]["persistence"] * signals[tid]["mean_confidence"]
        candidates = sorted([x["track_id"] for x in selected if signals[x["track_id"]]["persistence"] >= .5 and 0 < signals[x["track_id"]]["mean_area"] < .5], key=lambda tid: (-signals[tid]["quality"], tid))
        for tid in candidates:
            if all(temporal_iou(masks[tid], masks[k]) < .5 for k in committed): committed.add(tid)
        objects, metrics = evaluate(video, query_index, selected, masks, committed, args.verify_boundary_cache, args.evaluation_workers)
        gpu_peak = int(torch.cuda.max_memory_allocated() if args.device.startswith("cuda") else 0)
        result["videos"].append(dict(video_id=video.video_id, ordinal=source_ordinal, frame_names=[x.name for x in video.frame_paths], query_frame=query_path.name, query_frame_index=query_index, native_proposal_count=len(native), retained_topk_count=len(selected), native_proposals=native, retained_topk=selected, track_signals=signals, committed_track_ids=sorted(committed), objects=objects, metrics=metrics, wall_seconds=time.time()-started, peak_gpu_bytes=gpu_peak))
        print(f"[{completed_ordinal}/{len(chosen)}] {video.video_id}: native={len(native)} topk={len(selected)} committed={len(committed)}", flush=True)
        if completed_ordinal % args.checkpoint_every == 0 or completed_ordinal == len(chosen):
            write_json_atomic(args.output, result)
            if args.status_markdown: write_status_markdown(args.status_markdown, result, len(chosen))
    result["run_status"] = "complete"
    write_json_atomic(args.output, result)
    if args.status_markdown: write_status_markdown(args.status_markdown, result, len(chosen))
    print(f"wrote {args.output}")

